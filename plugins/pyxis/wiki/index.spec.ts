import { afterAll, expect, test } from 'bun:test'
import { mkdir, mkdtemp, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { renderIndex, renderSection } from './index'
import { parsePage } from './pages'

const HEADER = "# Index\n\nGenerated by pyxis from each page's `summary`. Do not edit.\n"

const text = (summary: string) => `---\nsummary: ${summary}\n---\n`
const p = (path: string, summary: string) => parsePage(path, text(summary))

test('one section per folder, overview first, then by path', () => {
  const pages = [
    p('billing/deploy.md', 'Deploy'),
    p('auth/tokens.md', 'Tokens'),
    p('billing/overview.md', 'What Billing is'),
  ]

  expect(renderIndex(pages)).toBe(
    HEADER +
      '\n## auth\n\n- [auth/tokens.md](auth/tokens.md) : Tokens\n' +
      '\n## billing\n\n- [billing/overview.md](billing/overview.md) : What Billing is\n' +
      '- [billing/deploy.md](billing/deploy.md) : Deploy\n',
  )
})

test('a summary with : # and quotes is kept whole', () => {
  expect(renderIndex([p('billing/a.md', '"Deploy: ECS # staging"')])).toContain(
    '- [billing/a.md](billing/a.md) : Deploy: ECS # staging\n',
  )
})

test('an empty wiki gives the header alone', () => {
  expect(renderIndex([])).toBe(HEADER)
})

// The command, run on a throwaway wiki.

const dirs: string[] = []

async function wiki(files: Record<string, string>): Promise<string> {
  const dir = await mkdtemp(join(tmpdir(), 'wiki-'))
  dirs.push(dir)
  for (const [path, content] of Object.entries(files)) {
    await mkdir(dirname(join(dir, path)), { recursive: true })
    await Bun.write(join(dir, path), content)
  }

  return dir
}

async function run(...args: string[]): Promise<{ code: number; out: string }> {
  const proc = Bun.spawn(['bun', join(import.meta.dir, 'index.ts'), ...args], { stdout: 'pipe', stderr: 'pipe' })
  const [out, err, code] = await Promise.all([
    new Response(proc.stdout).text(),
    new Response(proc.stderr).text(),
    proc.exited,
  ])

  return { code, out: out + err }
}

afterAll(async () => {
  await Promise.all(dirs.map(dir => rm(dir, { recursive: true })))
})

test('the command writes index.md for a valid wiki', async () => {
  const dir = await wiki({ 'billing/deploy.md': text('Deploy') })

  expect((await run(dir)).code).toBe(0)
  expect(await Bun.file(join(dir, 'index.md')).text()).toBe(renderIndex([p('billing/deploy.md', 'Deploy')]))
})

test('the command lists problems, exits 1 and writes nothing', async () => {
  const dir = await wiki({ 'billing/deploy.md': text('Deploy'), 'stray.md': text('Stray'), 'billing/bare.md': '# Bare\n' })
  const { code, out } = await run(dir)

  expect(code).toBe(1)
  expect(out).toContain('stray.md: not in a folder')
  expect(out).toContain('billing/bare.md: no frontmatter')
  expect(await Bun.file(join(dir, 'index.md')).exists()).toBe(false)
})

test('--check exits 1 on a stale index and leaves it untouched', async () => {
  const dir = await wiki({ 'billing/deploy.md': text('Deploy'), 'index.md': 'stale\n' })
  const { code, out } = await run('--check', dir)

  expect(code).toBe(1)
  expect(out).toContain('index.md is out of date')
  expect(await Bun.file(join(dir, 'index.md')).text()).toBe('stale\n')
})

test('--check exits 0 when the index is up to date', async () => {
  const dir = await wiki({ 'billing/deploy.md': text('Deploy') })
  await run(dir)

  expect((await run('--check', dir)).code).toBe(0)
})

test('renderSection gives one folder, overview first', () => {
  const pages = [p('billing/deploy.md', 'Deploy'), p('auth/tokens.md', 'Tokens'), p('billing/overview.md', 'What')]

  expect(renderSection(pages, 'billing')).toBe(
    '## billing\n\n- [billing/overview.md](billing/overview.md) : What\n- [billing/deploy.md](billing/deploy.md) : Deploy\n',
  )
})

test('the command without a wiki folder prints a usage and exits 2', async () => {
  const { code, out } = await run()

  expect(code).toBe(2)
  expect(out).toContain('usage:')
})
