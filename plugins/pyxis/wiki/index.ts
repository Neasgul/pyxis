// Generates wiki/index.md from each page's `summary`.
//
//   bun wiki/index.ts [--check] <wikiDir>
//
// Without --check it writes index.md; with it, it only says whether index.md is up to date.
// A page with a problem (no summary, too long, not in a folder…) stops both: nothing is written.

import { join } from 'node:path'
import { loadPages, pageProblems, type Page } from './pages'

const HEADER = "# Index\n\nGenerated by pyxis from each page's `summary`. Do not edit.\n"

/** Within a folder: the overview first, then by path. */
const byOverviewThenPath = (a: Page, b: Page) =>
  Number(b.path.endsWith('/overview.md')) - Number(a.path.endsWith('/overview.md')) || (a.path < b.path ? -1 : 1)

/** One folder's section of the index: its heading, then one line per page. */
export function renderSection(pages: Page[], folder: string): string {
  const lines = pages
    .filter(page => page.folder === folder)
    .sort(byOverviewThenPath)
    .map(page => `- [${page.path}](${page.path}) : ${page.summary}\n`)

  return `## ${folder}\n\n${lines.join('')}`
}

/** The index: one section per folder, one line per page. Expects pages without problems. */
export function renderIndex(pages: Page[]): string {
  const folders = [...new Set(pages.map(page => page.folder))].sort()

  return HEADER + folders.map(folder => `\n${renderSection(pages, folder)}`).join('')
}

async function main(args: string[]): Promise<number> {
  const check = args.includes('--check')
  const wikiDir = args.find(arg => arg !== '--check')
  if (!wikiDir) {
    console.error('usage: bun wiki/index.ts [--check] <wikiDir>')

    return 2
  }
  const pages = await loadPages(wikiDir)

  const problems = pages.flatMap(page => pageProblems(page).map(problem => `${page.path}: ${problem}`))
  if (problems.length > 0) {
    console.error(problems.join('\n'))

    return 1
  }

  const index = renderIndex(pages)
  const file = Bun.file(join(wikiDir, 'index.md'))
  if (!check) {
    await Bun.write(file, index)
    console.log(`index.md: ${pages.length} pages`)

    return 0
  }
  if (!(await file.exists()) || (await file.text()) !== index) {
    console.error('index.md is out of date')

    return 1
  }

  return 0
}

if (import.meta.main) {
  process.exit(await main(process.argv.slice(2)))
}
